  var FALLBACK = ["######", "#....#", "#....#", "#....#", "#....#", "#....#", "######", "......", "......"];

  function glyph(ch) { return G[ch] || G[ch.toUpperCase()] || FALLBACK; }

  /** Width of a string in source pixels, before scaling. */
  function measure(text, tracking) {
    tracking = tracking == null ? 1 : tracking;
    var w = 0;
    for (var i = 0; i < text.length; i++) {
      w += glyph(text[i])[0].length + (i < text.length - 1 ? tracking : 0);
    }
    return w;
  }

  /**
   * Paint text into a canvas, sizing the canvas to fit.
   * opts: { scale, color, tracking, shadow } — shadow is a second colour
   * dropped a pixel down and right, which is what gives display sizes weight.
   */
  function render(canvas, text, opts) {
    opts = opts || {};
    var scale = opts.scale || 2;
    var tracking = opts.tracking == null ? 1 : opts.tracking;
    var shadow = opts.shadow || null;
    var w = measure(text, tracking);
    var extra = shadow ? 1 : 0;

    canvas.width = (w + extra) * scale;
    canvas.height = (H + extra) * scale;
    var ctx = canvas.getContext("2d");
    ctx.imageSmoothingEnabled = false;
    ctx.clearRect(0, 0, canvas.width, canvas.height);

    function pass(dx, dy, fill) {
      ctx.fillStyle = fill;
      var cx = dx;
      for (var i = 0; i < text.length; i++) {
        var gl = glyph(text[i]);
        for (var y = 0; y < gl.length; y++) {
          for (var x = 0; x < gl[y].length; x++) {
            if (gl[y][x] === "#") ctx.fillRect((cx + x) * scale, (y + dy) * scale, scale, scale);
          }
        }
        cx += gl[0].length + tracking;
      }
    }
    if (shadow) pass(1, 1, shadow);
    pass(0, 0, opts.color || "#000");
    return canvas;
  }

  /**
   * Replace an element's text with pixel lettering, keeping the original
   * string in the DOM for screen readers and for find-on-page.
   */
  function apply(el, opts) {
    var text = (el.getAttribute("data-type") || el.textContent || "").trim();
    if (!text) return null;
    el.setAttribute("data-type", text);
    el.textContent = "";
    var sr = document.createElement("span");
    sr.textContent = text;
    sr.style.cssText = "position:absolute;width:1px;height:1px;overflow:hidden;clip:rect(0 0 0 0);white-space:nowrap";
    var cv = document.createElement("canvas");
    cv.setAttribute("aria-hidden", "true");
    render(cv, text, opts);
    cv.style.cssText = "display:block;height:auto;image-rendering:pixelated;max-width:100%";
    el.appendChild(sr);
    el.appendChild(cv);
    return cv;
  }

  root.CozyType = { H: H, glyphs: G, measure: measure, render: render, apply: apply };
